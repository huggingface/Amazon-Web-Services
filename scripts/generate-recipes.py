def replace_between(text: str, start: str, end: str, body: list[str], path: Path) -> str:
    pattern = re.compile(rf"(^[ \t]*{re.escape(start)}[ \t]*\n).*?(^[ \t]*{re.escape(end)}[ \t]*$)", re.S | re.M)
    if not pattern.search(text):
        raise SystemExit(f"{path}: markers {start!r} / {end!r} not found")
    block = "".join(line + "\n" for line in body)
    return pattern.sub(lambda m: m.group(1) + block + m.group(2), text, count=1)


def write_if_changed(path: Path, content: str) -> None:
    if not path.exists() or path.read_text() != content:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fetch", action="store_true", help=f"download recipes.jsonl and models.jsonl from {DATASET} first")
    args = parser.parse_args()
    if args.fetch:
        fetch_snapshots()

    metadata = load_models()
    models: dict[str, list[dict]] = defaultdict(list)
    for recipe in sorted(load_recipes(), key=sort_key):
        models[recipe["model_id"]].append(recipe)
    models = {model_id: one_per_instance(recipes) for model_id, recipes in sorted(models.items(), key=lambda item: item[0].lower())}
    missing = [model_id for model_id in models if model_id not in metadata]
    if missing:
        raise SystemExit(f"{MODELS_SNAPSHOT.name} has no entry for: {', '.join(missing)}")
    infos = {model_id: hub_info(model_id) for model_id in models}

    pages = {PAGES_DIR / f"{slug(model_id)}.md": model_page(model_id, recipes, infos[model_id], metadata[model_id]) for model_id, recipes in models.items()}
    pages[INDEX] = index_page(models, infos, metadata)
    for path in sorted(PAGES_DIR.rglob("*.md")):
        if path not in pages and GENERATED_MARKER in path.read_text():
            path.unlink()
            print(f"removed {path.relative_to(ROOT)}")
    for path, content in pages.items():
        write_if_changed(path, content)

    toctree = TOCTREE.read_text()
    write_if_changed(TOCTREE, replace_between(toctree, TOC_START, TOC_END, [], TOCTREE))


if __name__ == "__main__":
    main()
