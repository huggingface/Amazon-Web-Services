def cli_block(recipe: dict, gated: bool) -> list[str]:
    name = endpoint_name(recipe)
    if recipe["template_url"]:
        token = ' \\\n        ParameterKey=HuggingFaceToken,ParameterValue="$HF_TOKEN"' if gated else ""
        return [
            "```bash",
            f"aws cloudformation create-stack --region {DEFAULT_REGION} --stack-name {name} \\",
            f"    --template-url {recipe['template_url']} \\",
            "    --capabilities CAPABILITY_IAM \\",
            f"    --parameters ParameterKey=EndpointName,ParameterValue={name}{token}",
            "```",
        ]
    environment = dict(recipe["deployment"]["environment"])
    if gated:
        environment["HF_TOKEN"] = "HF_TOKEN_PLACEHOLDER"
    container = json.dumps({"Image": image_uri(recipe, DEFAULT_REGION), "Environment": environment}).replace(
        "HF_TOKEN_PLACEHOLDER", "'\"$HF_TOKEN\"'"
    )
    variant = json.dumps(
        [
            {
                "VariantName": "AllTraffic",
                "ModelName": name,
                "InstanceType": recipe["instance"]["type"],
                "InitialInstanceCount": 1,
                "InferenceAmiVersion": recipe["deployment"]["inference_ami_version"],
                "ContainerStartupHealthCheckTimeoutInSeconds": recipe["deployment"]["startup_health_check_timeout_s"],
            }
        ]
    )
    return [
        "```bash",
        f"aws sagemaker create-model --region {DEFAULT_REGION} --model-name {name} \\",
        "    --execution-role-arn arn:aws:iam::111122223333:role/your-sagemaker-execution-role \\",
        f"    --primary-container '{container}'",
        f"aws sagemaker create-endpoint-config --region {DEFAULT_REGION} --endpoint-config-name {name} \\",
        f"    --production-variants '{variant}'",
        f"aws sagemaker create-endpoint --region {DEFAULT_REGION} --endpoint-name {name} --endpoint-config-name {name}",
        "```",
    ]


def performance_table(recipe: dict) -> list[str]:
    metrics = {m["suite"]: m for m in recipe["metrics"]}
    rows = [(label, metrics[suite]) for suite, label in SUITES if suite in metrics]
    if not rows:
        return ["No benchmark results for this instance yet."]
    lines = [
        "| Workload | Concurrent requests | Tokens/s per user | Time to first token | Total tokens/s | Cost per 1M output tokens |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for label, m in rows:
        ttft = f"{m['median_ttft_ms'] / 1000:,.2f} s" if m["median_ttft_ms"] is not None else NA
        lines.append(
            f"| {label} | {fmt(m['concurrency'], 0)} | {fmt(per_user(m), 0)} | {ttft} | {fmt(m['output_throughput'], 0)} | "
            f"{usd(m['cost_per_million_output_tokens_usd'])} |"
        )
    return lines


def settings_table(recipe: dict) -> list[str]:
    image = recipe["image"]
    reference = f"{image['repository']}:{image['tag']}" if image["tag"] else image["repository"]
    lines = [
        f"Container `{reference}`" + (f", pinned to `{image['digest']}`." if image["digest"] else "."),
        "",
        "| Environment variable | Value |",
        "|---|---|",
    ]
    return lines + [f"| `{key}` | `{value}` |" for key, value in sorted(recipe["deployment"]["environment"].items())]


def instance_tabs(recipes: list[dict], body) -> list[str]:
    if len(recipes) == 1:
        return body(recipes[0])
    lines = ['<hfoptions id="instance">']
    for recipe in recipes:
        lines += [f'<hfoption id="{instance_label(recipe)}">', "", *body(recipe), "", "</hfoption>"]
    return [*lines, "</hfoptions>"]


ENGINE_NAMES = {"vllm": "vLLM", "sglang": "SGLang", "llama.cpp": "llama.cpp", "vllm-omni": "vLLM-Omni"}


def validation_lines(recipe: dict) -> list[str]:
    engine = recipe["engine"]
    engine_name = ENGINE_NAMES.get(engine["name"], engine["name"])
    lines = [
        f"Validated on {day(recipe['measured']['date'])} in {recipe['measured']['region']} with {engine_name} "
        f"{engine['version']}. Prices are {recipe['instance']['price_region']} on-demand."
    ]
    failed = [FAILED_CHECK_NAMES.get(check, check.replace("-", " ")) for check in recipe["failed_checks"] if check not in IGNORED_CHECKS]
    if failed:
        lines += ["", f"Failed checks on this instance: {', '.join(failed)}."]
    quotas = f"https://{DEFAULT_REGION}.console.aws.amazon.com/servicequotas/home/services/sagemaker/quotas"
    lines += [
        "",
        f"New AWS accounts often have no quota for this instance: request `{recipe['instance']['type']} for endpoint "
        f"usage` in [Service Quotas]({quotas}) before deploying.",
    ]
    return lines


def model_page(model_id: str, recipes: list[dict], info: dict, model: dict) -> str:
    facts = [model["parameters"] and f"{model['parameters']} parameters", model["context"] and f"{model['context']:,}-token context"]
    if info["license"]:
        facts.append(f"license [{info['license']}]({HUB}/{model_id})")
    header = (
        '<div class="not-prose my-4 flex items-start gap-3">'
        f"{logo(info, 'size-12')}"
        '<div class="flex flex-col gap-2">'
        f'<span class="text-base text-gray-700 dark:text-gray-300">{esc(model["description"])}</span>'
        f'<span class="flex flex-wrap gap-1.5 text-xs">{chips(recipes, None)}</span></div></div>'
    )
    gated = (
        f"This model is gated: accept its license on the [model page]({HUB}/{model_id}), then pass a "
        f"Hugging Face [access token]({HUB}/settings/tokens) as **HuggingFaceToken** (`HF_TOKEN` in the "
        "commands below)."
        if info["gated"]
        else ""
    )
    pick = "Pick an instance, then deploy" if len(recipes) > 1 else "Deploy"

    def deploy(recipe: dict) -> list[str]:
        summary = [f"**{instance_label(recipe)}**", f"{usd(recipe['instance']['price_per_hour_usd'])} per hour"]
        if recipe["context_length"]:
            summary.append(f"{recipe['context_length']:,}-token context")
        return [
            ", ".join(summary),
            "",
            *validation_lines(recipe),
            "",
            *(console_block(recipe) + [""] if recipe["template_url"] else []),
            *cli_block(recipe, info["gated"]),
        ]

    def invoke(recipe: dict) -> list[str]:
        return [
            "```python",
            "from openai import OpenAI",
            "from sagemaker.core.token_generator import generate_token",
            "",
            f'region, endpoint = "{DEFAULT_REGION}", "{endpoint_name(recipe)}"',
            "client = OpenAI(",
            '    base_url=f"https://runtime.sagemaker.{region}.amazonaws.com/endpoints/{endpoint}/openai/v1",',
            "    api_key=generate_token(region=region),",
            ")",
            "response = client.chat.completions.create(",
            f'    model="{model_id}",',
            '    messages=[{"role": "user", "content": "What is the capital of France?"}],',
            ")",
            "print(response.choices[0].message.content)",
            "```",
        ]

    def cleanup(recipe: dict) -> list[str]:
        name = endpoint_name(recipe)
        if recipe["template_url"]:
            commands = [f"aws cloudformation delete-stack --region {DEFAULT_REGION} --stack-name {name}"]
        else:
            commands = [
                f"aws sagemaker delete-endpoint --region {DEFAULT_REGION} --endpoint-name {name}",
                f"aws sagemaker wait endpoint-deleted --region {DEFAULT_REGION} --endpoint-name {name}",
                f"aws sagemaker delete-endpoint-config --region {DEFAULT_REGION} --endpoint-config-name {name}",
                f"aws sagemaker delete-model --region {DEFAULT_REGION} --model-name {name}",
            ]
        return ["```bash", *commands, "```"]

    lines = [
        f"# Deploy {model_id} on Amazon SageMaker AI",
        "",
        GENERATED_NOTE,
        "",
        header,
        "",
        f"[{model_id}]({HUB}/{model_id}) by [{info['org_name']}]({HUB}/{info['org']})"
        + (f": {', '.join(fact for fact in facts if fact)}." if any(facts) else "."),
        "",
        "## Deploy",
        "",
        f"{pick} from the AWS CloudFormation console or with the AWS CLI command. Both create the endpoint in "
        f"`{DEFAULT_REGION}`; not every instance type is available in every region. The endpoint is ready after 10 to "
        "30 minutes. To deploy from Python, see [Deploy a model](./deploy-a-recipe).",
        "",
    ]
    if gated:
        lines += [gated, ""]
    lines += [
        *instance_tabs(recipes, deploy),
        "",
        "## Performance",
        "",
        *instance_tabs(recipes, performance_table),
        "",
        "## Engine settings",
        "",
        *instance_tabs(recipes, settings_table),
        "",
        "## Send requests",
        "",
        "The endpoint serves the OpenAI chat completions API. Any OpenAI client works with a short-lived SageMaker token:",
        "",
        *instance_tabs(recipes, invoke),
        "",
        "## Clean up",
        "",
        "Endpoints are billed per hour while they run. Delete the stack when you are done, from the CloudFormation "
        "console or with the command below. If you changed the stack name when deploying, use that name instead:",
        "",
        *instance_tabs(recipes, cleanup),
        "",
    ]
    return "\n".join(lines)


def replace_between(text: str, start: str, end: str, body: list[str], path: Path) -> str:
    pattern = re.compile(rf"(^[ \t]*{re.escape(start)}[ \t]*\n).*?(^[ \t]*{re.escape(end)}[ \t]*$)", re.S | re.M)
    if not pattern.search(text):
        raise SystemExit(f"{path}: markers {start!r} / {end!r} not found")
    block = "".join(line + "\n" for line in body)
    return pattern.sub(lambda m: m.group(1) + block + m.group(2), text, count=1)


def write_if_changed(path: Path, content: str) -> None:
    if not path.exists() or path.read_text() != content:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fetch", action="store_true", help=f"download the snapshots from {DATASET} and the Hub first")
    args = parser.parse_args()
    if args.fetch:
        fetch_snapshots()

    metadata = load_models()
    infos = load_hub()
    models: dict[str, list[dict]] = defaultdict(list)
    for recipe in sorted(load_recipes(), key=default_order):
        models[recipe["model_id"]].append(recipe)
    models = {model_id: one_per_instance(recipes) for model_id, recipes in sorted(models.items(), key=lambda item: item[0].lower())}
    for snapshot, rows in ((MODELS_SNAPSHOT, metadata), (HUB_SNAPSHOT, infos)):
        missing = [model_id for model_id in models if model_id not in rows]
        if missing:
            raise SystemExit(f"{snapshot.name} has no entry for: {', '.join(missing)}")
    print(f"published {len(models)} models")

    pages = {PAGES_DIR / f"{slug(model_id)}.md": model_page(model_id, recipes, infos[model_id], metadata[model_id]) for model_id, recipes in models.items()}
    pages[INDEX] = index_page(models, infos, metadata)
    for path, content in pages.items():
        if any(character in content for character in FORBIDDEN):
            raise SystemExit(f"{path.relative_to(ROOT)}: contains an em dash or a mid-dot")
    for path in sorted(PAGES_DIR.rglob("*.md")):
        if path not in pages and GENERATED_MARKER in path.read_text():
            path.unlink()
            print(f"removed {path.relative_to(ROOT)}")
    for path, content in pages.items():
        write_if_changed(path, content)

    toctree = TOCTREE.read_text()
    write_if_changed(TOCTREE, replace_between(toctree, TOC_START, TOC_END, [], TOCTREE))


if __name__ == "__main__":
    main()
