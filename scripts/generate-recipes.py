def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def esc(value) -> str:
    return html.escape(str(value), quote=True).replace("{", "&#123;")


def plain(text: str | None) -> str | None:
    return re.sub(r"\s*[\u2014\u00b7]\s*", ", ", text) if text else text


def fmt(value, digits: int) -> str:
    if value is None:
        return NA
    return f"{value:,.{digits}f}"


def usd(value) -> str:
    if value is None:
        return NA
    return f"${value:,.2f}"


def day(value: str) -> str:
    date = datetime.strptime(value, "%Y-%m-%d")
    return f"{date.day} {date:%b %Y}"


def month(value: str) -> str:
    return datetime.strptime(value, "%Y-%m-%d").strftime("%b %Y") if value else ""


def per_user(metric: dict) -> float | None:
    tpot = metric.get("median_tpot_ms")
    return 1000 / tpot if tpot else None


def image_reference(recipe: dict) -> str:
    image = recipe["image"]
    return f"{image['repository']}@{image['digest']}" if image["digest"] else f"{image['repository']}:{image['tag']}"


def image_uri(recipe: dict, region: str) -> str:
    return f"{recipe['image']['registry_account']}.dkr.ecr.{region}.amazonaws.com/{image_reference(recipe)}"


def endpoint_name(recipe: dict) -> str:
    name = slug(f"{recipe['model_id'].split('/')[-1]}-{recipe['instance']['type'].removeprefix('ml.')}")
    if not name[0].isalpha():
        name = f"hf-{name}"
    return name[:63].strip("-")


def console_url(recipe: dict, region: str) -> str:
    query = urllib.parse.urlencode(
        {"templateURL": recipe["template_url"], "stackName": endpoint_name(recipe), "param_EndpointName": endpoint_name(recipe)}
    )
    return f"https://console.aws.amazon.com/cloudformation/home?region={region}#/stacks/quickcreate?{query}"


def hub_token() -> str | None:
    token = os.environ.get("HF_TOKEN")
    if token:
        return token
    cached = Path(os.environ.get("HF_HOME", Path.home() / ".cache" / "huggingface")) / "token"
    return cached.read_text().strip() if cached.exists() else None


def hub_get(path: str, token: str) -> dict | None:
    request = urllib.request.Request(f"{HUB}/api/{path}", headers={"Authorization": f"Bearer {token}"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return None
        raise


@functools.cache
def owner_profile(owner: str, token: str) -> dict:
    for kind in ("organizations", "users"):
        profile = hub_get(f"{kind}/{owner}/overview", token)
        if profile is not None:
            return {"name": profile.get("fullname") or owner, "avatar": profile.get("avatarUrl")}
    raise SystemExit(f"Hub owner not found: {owner}")


def hub_row(model_id: str, token: str) -> dict:
    query = "&".join(f"expand[]={field}" for field in ["gated", "pipeline_tag", "safetensors", "cardData", "createdAt", "trendingScore"])
    info = hub_get(f"models/{model_id}?{urllib.parse.quote(query, safe='=&')}", token)
    if info is None:
        raise SystemExit(f"Hub model not found: {model_id}")
    card = info.get("cardData") or {}
    org = info["id"].split("/")[0]
    owner = owner_profile(org, token)
    return {
        "model_id": model_id,
        "org": org,
        "org_name": owner["name"],
        "org_avatar": owner["avatar"],
        "gated": bool(info.get("gated")),
        "pipeline_tag": info.get("pipeline_tag"),
        "parameters": (info.get("safetensors") or {}).get("total"),
        "license": card.get("license_name") or card.get("license"),
        "created": (info.get("createdAt") or "")[:10],
        "trending": info.get("trendingScore") or 0,
    }


def fetch_hub(token: str) -> None:
    model_ids = sorted({row["model_id"] for row in read_jsonl(RECIPES_SNAPSHOT, ["model_id"])}, key=str.lower)
    rows = [json.dumps(hub_row(model_id, token), sort_keys=True) for model_id in model_ids]
    write_if_changed(HUB_SNAPSHOT, "".join(f"{row}\n" for row in rows))


def fetch_snapshots() -> None:
    token = hub_token()
    if not token:
        raise SystemExit(f"--fetch needs a Hugging Face token that can read {DATASET}: set HF_TOKEN or run `hf auth login`.")
    for path in (RECIPES_SNAPSHOT, MODELS_SNAPSHOT):
        url = f"{HUB}/datasets/{DATASET}/resolve/main/{path.name}"
        request = urllib.request.Request(url, headers={"Authorization": f"Bearer {token}"})
        with urllib.request.urlopen(request, timeout=60) as response:
            write_if_changed(path, response.read().decode())
    fetch_hub(token)


def read_jsonl(path: Path, fields: list[str]) -> list[dict]:
    if not path.exists():
        raise SystemExit(f"{path} not found: run `python scripts/generate-recipes.py --fetch` first.")
    rows = []
    for line, text in enumerate(path.read_text().splitlines(), start=1):
        if not text.strip():
            continue
        row = json.loads(text)
        missing = [field for field in fields if field not in row]
        if missing:
            raise SystemExit(f"{path.name}:{line}: missing {', '.join(missing)}")
        rows.append(row)
    return rows


def recipe_from_row(row: dict) -> dict:
    where = f"{RECIPES_SNAPSHOT.name}: {row['model_id']} {row['recipe']}"
    match = IMAGE_PATTERN.match(row["image"])
    if not match:
        raise SystemExit(f"{where}: unsupported image {row['image']}")
    measured, checks, failed = row["measured"], row["capabilities"], row["failed_checks"]
    if measured is not None and not (
        isinstance(measured, dict) and DATE_PATTERN.match(str(measured.get("date"))) and measured.get("region")
    ):
        raise SystemExit(f"{where}: malformed measured {measured!r}")
    if not isinstance(checks, dict) or any(checks.get(check) not in (True, False, None) for check in CHECKS):
        raise SystemExit(f"{where}: malformed capabilities {checks!r}")
    if not isinstance(failed, list) or not all(isinstance(check, str) for check in failed):
        raise SystemExit(f"{where}: malformed failed_checks {failed!r}")
    if not isinstance(row["instance"].get("price_per_hour_usd"), (int, float, type(None))):
        raise SystemExit(f"{where}: malformed price {row['instance'].get('price_per_hour_usd')!r}")
    account, repository, tag, digest = match.groups()
    return {
        "id": f"{slug(row['model_id'])}--{row['recipe']}",
        "model_id": row["model_id"],
        "context_length": row["context_length"],
        "engine": row["engine"],
        "image": {"registry_account": account, "repository": repository, "tag": tag, "digest": digest},
        "instance": {**row["instance"], "accelerator": plain(row["instance"].get("accelerator"))},
        "deployment": {**row["deployment"], "environment": json.loads(row["environment"])},
        "metrics": row["metrics"],
        "model_revision": row["model_revision"],
        "measured": measured,
        "checks": {check: checks.get(check) for check in CHECKS},
        "failed_checks": failed,
        "template_url": row["cloudformation_template_url"],
    }


def exclusion_reason(recipe: dict) -> str | None:
    """Why a recipe is not published, or None when it is.

    The catalog lists only recipes that Kitchen deployed and validated on SageMaker AI: the run is
    recorded in `measured`, the chat check passed, the image is the Hugging Face vLLM DLC, the model
    revision is pinned, and the instance has a us-east-1 on-demand price.
    """
    if recipe["measured"] is None:
        return "not validated on SageMaker AI"
    if recipe["checks"]["chat"] is not True:
        return "chat check did not pass"
    if recipe["image"]["repository"] != PUBLISHED_REPOSITORY:
        return f"image {recipe['image']['repository']} is not {PUBLISHED_REPOSITORY}"
    if not recipe["model_revision"]:
        return "no model revision"
    if recipe["instance"]["price_per_hour_usd"] is None or recipe["instance"].get("price_region") != DEFAULT_REGION:
        return f"no {DEFAULT_REGION} price"
    return None


def load_recipes() -> list[dict]:
    recipes, skipped = {}, 0
    for row in read_jsonl(RECIPES_SNAPSHOT, RECIPE_FIELDS):
        recipe = recipe_from_row(row)
        reason = exclusion_reason(recipe)
        if reason is None:
            recipes.setdefault(recipe["id"], recipe)
        elif recipe["measured"] is None:
            skipped += 1
        else:
            print(f"excluded {recipe['model_id']} {recipe['instance']['type']}: {reason}")
    print(f"published {len(recipes)} recipes; skipped {skipped} rows not validated on SageMaker AI")
    return list(recipes.values())


def load_models() -> dict[str, dict]:
    return {row["model_id"]: {**row, "description": plain(row["description"])} for row in read_jsonl(MODELS_SNAPSHOT, MODEL_FIELDS)}


def load_hub() -> dict[str, dict]:
    return {row["model_id"]: {**row, "org_name": plain(row["org_name"]), "license": plain(row["license"])} for row in read_jsonl(HUB_SNAPSHOT, HUB_FIELDS)}


def default_order(recipe: dict) -> tuple:
    return (not recipe["metrics"], recipe["instance"]["price_per_hour_usd"], recipe["instance"]["type"], recipe["id"])


def one_per_instance(recipes: list[dict]) -> list[dict]:
    def latest(recipe: dict) -> tuple:
        version = tuple(int(part) for part in re.findall(r"\d+", recipe["engine"]["version"] or ""))
        return (recipe["measured"]["date"], version)

    best: dict[str, dict] = {}
    for recipe in recipes:
        current = best.get(recipe["instance"]["type"])
        if current is None or latest(recipe) > latest(current):
            best[recipe["instance"]["type"]] = recipe
    return [recipe for recipe in recipes if best[recipe["instance"]["type"]] is recipe]


def logo(info: dict, size: str) -> str:
    if not info["org_avatar"]:
        return ""
    return f'<img src="{esc(info["org_avatar"])}" alt="{esc(info["org_name"])} logo" loading="lazy" {LOGO_STYLE} class="{size} {LOGO_CLASS}">'


def chips(recipes: list[dict], parameters: str | None) -> str:
    rendered = [
        f'<span class="rounded-md px-1.5 py-0.5 {color}">{esc(label)}</span>'
        for check, label, color in CAPABILITIES
        if all(recipe["checks"][check] is True for recipe in recipes)
    ]
    if parameters:
        rendered.append(f'<span class="rounded-md px-1.5 py-0.5 {NEUTRAL_CHIP}">{esc(parameters)}</span>')
    return "".join(rendered)


def instance_label(recipe: dict) -> str:
    instance = recipe["instance"]
    if not instance["accelerator"]:
        return instance["type"]
    gpus = f"{instance['gpus']}x " if instance["gpus"] and instance["gpus"] > 1 else ""
    return f"{gpus}{instance['accelerator']} ({instance['type']})"


def card(model_id: str, recipes: list[dict], info: dict, model: dict) -> str:
    default = recipes[0]
    if len(recipes) == 1:
        footer = [f"{usd(default['instance']['price_per_hour_usd'])}/h"]
    else:
        footer = [f"from {usd(min(r['instance']['price_per_hour_usd'] for r in recipes))}/h", f"{len(recipes)} instances"]
    if info["gated"]:
        footer.append("gated")
    context = default["context_length"] or model["context"]
    details = [
        ("Instance", instance_label(default)),
        ("Context", f"{context:,} tokens" if context else NA),
        ("On the Hub since", month(info["created"]) or NA),
    ]
    data = {"search": f"{model_id.lower()} {info['org_name'].lower()} {model['description'].lower()}"}
    attributes = " ".join(f'data-{key}="{esc(value)}"' for key, value in data.items())
    deploy = (
        f'<a class="btn h-8 no-underline!" target="_blank" rel="noopener" href="{esc(console_url(default, DEFAULT_REGION))}">'
        "Deploy on SageMaker ↗</a>"
        if default["template_url"]
        else ""
    )
    rows = "".join(
        f'<dt class="text-gray-500 dark:text-gray-400">{esc(label)}</dt><dd class="col-span-2 text-gray-900 dark:text-gray-100">{esc(value)}</dd>'
        for label, value in details
    )
    return (
        f"<div {attributes}>"
        '<details class="group details-reset rounded-xl border border-gray-200 shadow-sm transition '
        'hover:border-gray-300 dark:border-gray-800 dark:hover:border-gray-700">'
        '<summary class="flex min-h-44 cursor-pointer select-none flex-col gap-2 p-4">'
        '<span class="flex items-center gap-2">'
        f"{logo(info, 'size-8')}"
        f'<span class="min-w-0 flex-1 truncate text-sm text-gray-500 dark:text-gray-400">{esc(info["org_name"])}</span>'
        '<span class="shrink-0 text-gray-400 transition-transform group-open:rotate-180" aria-hidden="true">▾</span>'
        "</span>"
        f'<span class="line-clamp-2 break-all text-lg font-semibold leading-snug text-gray-900 dark:text-white" title="{esc(model_id)}">{esc(model_id.split("/", 1)[1])}</span>'
        f'<span class="line-clamp-2 text-sm text-gray-600 dark:text-gray-400">{esc(model["description"])}</span>'
        f'<span class="flex flex-wrap gap-1.5 text-xs">{chips(recipes, model["parameters"])}</span>'
        f'<span class="mt-auto truncate text-sm text-gray-500 dark:text-gray-400">{esc(", ".join(footer))}</span>'
        "</summary>"
        '<div class="border-t border-gray-200 px-4 py-3 text-sm dark:border-gray-800">'
        f'<dl class="grid grid-cols-3 gap-x-4 gap-y-1">{rows}</dl>'
        '<div class="mt-3 flex flex-wrap items-center gap-4">'
        f"{deploy}"
        f'<a class="{LINK_CLASS}" href="{{base}}{slug(model_id)}">All details →</a>'
        "</div></div></details></div>"
    )


def card_grid(cards: list[str], base: str, extra: str = "") -> str:
    return f'<div {extra}class="mt-4 grid grid-cols-1 items-start gap-3 sm:grid-cols-2 lg:grid-cols-3">{"".join(cards).replace("{base}", base)}</div>'


def catalog(models: dict[str, list[dict]], infos: dict[str, dict], metadata: dict[str, dict]) -> list[str]:
    cards = [card(model_id, model_recipes, infos[model_id], metadata[model_id]) for model_id, model_recipes in models.items()]
    return [
        f'<div class="not-prose my-6" {{@attach {CATALOG_SCRIPT}}}>',
        "",
        '<div><input type="search" name="q" placeholder="Search models" aria-label="Search models" '
        'class="h-9 w-full rounded-lg border border-gray-200 bg-white px-3 text-sm dark:border-gray-700 dark:bg-gray-950">'
        f'<div class="mt-2 text-sm text-gray-500 dark:text-gray-400" data-count>{len(models)} models</div></div>',
        "",
        card_grid(cards, "./", "data-grid "),
        "",
        '<p data-empty hidden class="mt-4 text-sm text-gray-500">No model matches your search.</p>',
        "",
        "</div>",
    ]


def index_page(models: dict[str, list[dict]], infos: dict[str, dict], metadata: dict[str, dict]) -> str:
    trending = sorted(models, key=lambda model_id: (-infos[model_id]["trending"], model_id.lower()))[:TRENDING_ON_OVERVIEW]
    trending_cards = [card(model_id, models[model_id], infos[model_id], metadata[model_id]) for model_id in trending]
    lines = [
        "# Deploy open models on Amazon SageMaker AI",
        "",
        GENERATED_NOTE,
        "",
        "Recipes are deployment configurations for open models from the Hugging Face Hub on Amazon SageMaker AI. Each "
        "recipe sets the instance type, the Hugging Face vLLM Deep Learning Container, and the engine settings, and was "
        "deployed and checked on SageMaker AI before being listed here. Each model page has a CloudFormation template "
        "that you can launch from the AWS console or with the AWS CLI, benchmark results where available, and the code "
        "to send requests.",
        "",
        "To deploy from Python, see [Deploy a model](./deploy-a-recipe). To learn how recipes are checked and "
        "benchmarked, see [How deployments are benchmarked](./methodology).",
        "",
        "## Trending",
        "",
        f'<div class="not-prose">{card_grid(trending_cards, "./")}</div>',
        "",
        "## All models",
        "",
        *catalog(models, infos, metadata),
        "",
    ]
    return "\n".join(lines)


