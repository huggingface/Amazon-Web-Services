"""Generate the SageMaker recipes catalog from the recipes dataset.

The recipes live in the Hub dataset `hf-rev/sagemaker-recipes`: `recipes.jsonl` has one row
per recipe and `models.jsonl` one row per model. `--fetch` downloads both into recipes/ (needs
a token that can read the dataset, from HF_TOKEN or the `hf auth login` cache) and writes the
Hub metadata of each model to recipes/hub.jsonl. Without `--fetch`, the pages are generated
from those committed snapshots only, so the docs build needs no token and no network access.

Only recipes that pass `exclusion_reason` are published. Writes the catalog to
source/recipes/index.md, one page per model to source/recipes/<model-slug>.md, and the
navigation entries in source/_toctree.yml.
"""

